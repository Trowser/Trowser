using System.IO;
using System.Reflection;
using System.Text;
using System.Web;

namespace Trowser.SessionLog;

/// <summary>
/// Converts a session log .md file into a self-contained, styled HTML report.
/// </summary>
public static class HtmlReportGenerator
{
    public static void Generate(string mdPath, string htmlPath)
    {
        var mdContent = ReadAllTextShared(mdPath);
        var mdDir = Path.GetDirectoryName(Path.GetFullPath(mdPath))!;

        var version = Assembly.GetExecutingAssembly().GetName().Version;
        var versionText = version != null
            ? $"{version.Major}.{version.Minor}.{version.Build}"
            : "1.0.0";

        var sb = new StringBuilder();
        sb.AppendLine("<!DOCTYPE html>");
        sb.AppendLine("<html lang=\"en\">");
        sb.AppendLine("<head>");
        sb.AppendLine("<meta charset=\"UTF-8\">");
        sb.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">");
        sb.AppendLine($"<title>Trowser Session Report</title>");
        sb.AppendLine("<style>");
        sb.AppendLine(CssStyles);
        sb.AppendLine("</style>");
        sb.AppendLine("</head>");
        sb.AppendLine("<body>");
        sb.AppendLine("<div class=\"container\">");
        sb.AppendLine("<header>");
        sb.AppendLine("<h1>🧪 Trowser Session Report</h1>");
        sb.AppendLine($"<p class=\"meta\">Generated by Trowser v{versionText} on {DateTime.Now:yyyy-MM-dd HH:mm:ss}</p>");
        sb.AppendLine("</header>");
        sb.AppendLine("<main>");

        RenderMarkdown(sb, mdContent, mdDir);

        sb.AppendLine("</main>");
        sb.AppendLine("</div>");
        sb.AppendLine("</body>");
        sb.AppendLine("</html>");

        File.WriteAllText(htmlPath, sb.ToString(), new UTF8Encoding(false));
    }

    /// <summary>
    /// Read a file even when the session logger still has it open for append
    /// (<see cref="FileShare.ReadWrite"/>).
    /// </summary>
    private static string ReadAllTextShared(string path)
    {
        using var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite);
        using var reader = new StreamReader(fs, Encoding.UTF8, detectEncodingFromByteOrderMarks: true);
        return reader.ReadToEnd();
    }

    private static void RenderMarkdown(StringBuilder sb, string md, string mdDir)
    {
        var lines = md.Split('\n');
        var inCodeBlock = false;

        for (int i = 0; i < lines.Length; i++)
        {
            var line = lines[i].TrimEnd('\r');

            // Code block toggle
            if (line.StartsWith("```"))
            {
                if (inCodeBlock)
                {
                    sb.AppendLine("</code></pre>");
                    inCodeBlock = false;
                }
                else
                {
                    var lang = line.Length > 3 ? $" class=\"lang-{Esc(line[3..].Trim())}\"" : "";
                    sb.AppendLine($"<pre><code{lang}>");
                    inCodeBlock = true;
                }
                continue;
            }

            if (inCodeBlock)
            {
                sb.AppendLine(Esc(line));
                continue;
            }

            // Horizontal rule
            if (line == "---")
            {
                sb.AppendLine("<hr>");
                continue;
            }

            // Headings
            if (line.StartsWith("# "))
            {
                sb.AppendLine($"<h2>{RenderInline(line[2..], mdDir)}</h2>");
                continue;
            }

            // Bold lines (**Started:** etc.)
            if (line.StartsWith("**") || line.StartsWith("*Session"))
            {
                sb.AppendLine($"<p>{RenderInline(line, mdDir)}</p>");
                continue;
            }

            // Entry lines starting with backtick timestamp
            if (line.StartsWith("`") && line.Contains("**"))
            {
                sb.AppendLine($"<div class=\"entry\">{RenderInline(line, mdDir)}</div>");
                continue;
            }

            // Empty lines
            if (string.IsNullOrWhiteSpace(line))
            {
                continue;
            }

            // Default: paragraph
            sb.AppendLine($"<p>{RenderInline(line, mdDir)}</p>");
        }

        if (inCodeBlock)
            sb.AppendLine("</code></pre>");
    }

    private static string RenderInline(string text, string mdDir)
    {
        var result = new StringBuilder();
        int pos = 0;

        while (pos < text.Length)
        {
            // Screenshot image: ![alt](path)
            if (pos < text.Length - 1 && text[pos] == '!' && text[pos + 1] == '[')
            {
                var altEnd = text.IndexOf(']', pos + 2);
                var pathStart = altEnd >= 0 && altEnd + 1 < text.Length && text[altEnd + 1] == '(' ? altEnd + 2 : -1;
                var pathEnd = pathStart >= 0 ? text.IndexOf(')', pathStart) : -1;

                if (pathEnd > pathStart)
                {
                    var alt = text[(pos + 2)..altEnd];
                    var imgPath = text[pathStart..pathEnd];

                    // Try to embed image as base64
                    var fullPath = Path.Combine(mdDir, imgPath.Replace('/', '\\'));
                    if (File.Exists(fullPath))
                    {
                        try
                        {
                            var bytes = File.ReadAllBytes(fullPath);
                            var b64 = Convert.ToBase64String(bytes);
                            var ext = Path.GetExtension(fullPath).ToLowerInvariant().TrimStart('.');
                            var mime = ext == "jpg" ? "jpeg" : ext;
                            result.Append($"<img src=\"data:image/{mime};base64,{b64}\" alt=\"{Esc(alt)}\" class=\"screenshot\">");
                        }
                        catch
                        {
                            result.Append($"<img src=\"{Esc(imgPath)}\" alt=\"{Esc(alt)}\" class=\"screenshot\">");
                        }
                    }
                    else
                    {
                        result.Append($"<img src=\"{Esc(imgPath)}\" alt=\"{Esc(alt)}\" class=\"screenshot\">");
                    }
                    pos = pathEnd + 1;
                    continue;
                }
            }

            // Bold: **text**
            if (pos < text.Length - 1 && text[pos] == '*' && text[pos + 1] == '*')
            {
                var end = text.IndexOf("**", pos + 2, StringComparison.Ordinal);
                if (end > pos + 2)
                {
                    result.Append($"<strong>{Esc(text[(pos + 2)..end])}</strong>");
                    pos = end + 2;
                    continue;
                }
            }

            // Italic: *text*
            if (text[pos] == '*' && (pos == 0 || text[pos - 1] != '*') &&
                pos + 1 < text.Length && text[pos + 1] != '*')
            {
                var end = text.IndexOf('*', pos + 1);
                if (end > pos + 1 && (end + 1 >= text.Length || text[end + 1] != '*'))
                {
                    result.Append($"<em>{Esc(text[(pos + 1)..end])}</em>");
                    pos = end + 1;
                    continue;
                }
            }

            // Inline code: `text`
            if (text[pos] == '`')
            {
                var end = text.IndexOf('`', pos + 1);
                if (end > pos + 1)
                {
                    result.Append($"<code>{Esc(text[(pos + 1)..end])}</code>");
                    pos = end + 1;
                    continue;
                }
            }

            result.Append(Esc(text[pos].ToString()));
            pos++;
        }

        return result.ToString();
    }

    private static string Esc(string s) => HttpUtility.HtmlEncode(s);

